import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Replace only the two broken string/object union models produced by OpenAPI
 * Generator 7.22 (escaped C++ template names and primitive method calls).
 * The template preserves VariantType/getVariant/setVariant and adds ModelBase
 * compatibility required by generated multipart/form request builders.
 */
const ownRoot = fileURLToPath(new URL("..", import.meta.url));
const root = process.argv[2] ? resolve(process.argv[2]) : ownRoot;
const template = await readFile(
  resolve(ownRoot, "quality/templates/flow-header.h"),
  "utf8",
);
const unions = [
  ["SendFlow_request_header", "std::shared_ptr<Object>", "is_object"],
  ["SendFlow_request_1_header", "std::shared_ptr<Object>", "is_object"],
  [
    "CreateSettings_request_webhookUrl",
    "std::vector<utility::string_t>",
    "is_array",
  ],
  [
    "GetWebhook_200_response_webhookUrl",
    "std::vector<utility::string_t>",
    "is_array",
  ],
  [
    "ListSettings_200_response_webhookUrl",
    "std::vector<utility::string_t>",
    "is_array",
  ],
  [
    "SetWebhook_200_response_webhookUrl",
    "std::vector<utility::string_t>",
    "is_array",
  ],
  [
    "SetWebhook_request_webhookUrl",
    "std::vector<utility::string_t>",
    "is_array",
  ],
  [
    "SendContact_request_contact_name",
    "std::map<utility::string_t, std::shared_ptr<AnyType>>",
    "is_object",
  ],
];
for (const [name, alternative, kind] of unions) {
  const header = resolve(root, `include/one-msg-sdk/model/${name}.h`);
  await readFile(header);
  const validation =
    alternative === "std::shared_ptr<Object>"
      ? '        if (std::holds_alternative<std::shared_ptr<Object>>(m_variantValue) && !std::get<std::shared_ptr<Object>>(m_variantValue)) throw std::invalid_argument("Flow header cannot be null");'
      : "        // Every stored alternative is a value; JSON null is rejected by fromJson.";
  await writeFile(
    header,
    template
      .replaceAll("@NAME@", name)
      .replaceAll("@ALTERNATIVE@", alternative)
      .replaceAll("@KIND@", kind)
      .replaceAll("@VALIDATE@", validation),
  );
  await writeFile(
    resolve(root, `src/model/${name}.cpp`),
    `// Generated by quality/postprocess.mjs; implementation is inline to preserve union templates.\n#include "one-msg-sdk/model/${name}.h"\n`,
  );
}
const clientPath = resolve(root, "include/one-msg-sdk/ApiClient.h");
const client = await readFile(clientPath, "utf8");
const mapAnchor =
  "    static utility::string_t parameterToString(const ModelBase& value);";
const mapMarker = "// 1MSG: map form values use generated JSON serializers.";
if (!client.includes(mapMarker)) {
  if (!client.includes(mapAnchor))
    throw new Error("C++ request serializer changed");
  await writeFile(
    clientPath,
    client.replace(
      mapAnchor,
      `${mapAnchor}\n    ${mapMarker}\n    template<class T>\n    static utility::string_t parameterToString(const std::map<utility::string_t, T>& value) {\n        return ModelBase::toJson(value).serialize();\n    }`,
    ),
  );
}

const cmakePath = resolve(root, "CMakeLists.txt");
let cmake = await readFile(cmakePath, "utf8");
if (!cmake.includes("find_package(OpenSSL REQUIRED)"))
  cmake = cmake.replace(
    "find_package(Boost REQUIRED)",
    "find_package(Boost REQUIRED)\nfind_package(OpenSSL REQUIRED)",
  );
cmake = cmake.replace(
  "PUBLIC Boost::headers cpprestsdk::cpprest)",
  "PUBLIC Boost::headers cpprestsdk::cpprest OpenSSL::SSL OpenSSL::Crypto)",
);
await writeFile(cmakePath, cmake);
const packagePath = resolve(root, "Config.cmake.in");
let packageConfig = await readFile(packagePath, "utf8");
if (!packageConfig.includes("find_dependency(OpenSSL)"))
  packageConfig = packageConfig.replace(
    "@PACKAGE_INIT@",
    "@PACKAGE_INIT@\n\ninclude(CMakeFindDependencyMacro)\nfind_dependency(Boost)\nfind_dependency(cpprestsdk)\nfind_dependency(OpenSSL)",
  );
await writeFile(packagePath, packageConfig);
